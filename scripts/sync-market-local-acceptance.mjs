import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=readFileSync(path.join(root,'compatibility/market-local-acceptance/profile.json'));
const value=JSON.parse(source);
assert.equal(value.contractId,'market-local-acceptance/1');
assert.equal(value.contractVersion,'0.2.0');assert.equal(value.release,false);
assert.equal(value.selector,'YIJIE_MARKET_LOCAL_ACCEPTANCE');
assert.equal(value.dataDirectory,'market-local-acceptance');
assert.equal(value.runLabelPattern,'^[a-z0-9][a-z0-9-]{0,47}$');
assert.equal(value.mcpEndpoint,'http://127.0.0.1:18085/mcp');
assert.equal(value.modelEndpoint,'http://127.0.0.1:18083/v1');
assert.equal(value.provider.resource,value.mcpEndpoint);
assert.equal(value.catalogEntry.serviceId,value.provider.serviceId);
assert.equal(value.provider.authMode,'none');
assert.equal(value.workerArgument,'--broker-local-acceptance-stdio');
assert.deepEqual(value.tool.inputSchema.properties.scenario.enum,['structured','dual','error','slow']);
const schema=JSON.parse(readFileSync(path.join(root,'sdks/jsonschema/market-connectors.schema.json')));
const ajv=new Ajv({strict:false});addFormats(ajv);ajv.addSchema(schema);
const validate=ajv.getSchema(schema.$id+'#/$defs/CatalogEntry');assert(validate(value.catalogEntry),JSON.stringify(validate.errors));
ajv.compile(value.tool.inputSchema);
const outputs=['../yijie-desktop/contracts/market-local-acceptance.json','../yijie-connectors/catalog/market-local-acceptance.json','../yijie-agent-host/internal/marketbroker/market-local-acceptance.json'];
const check=process.argv.includes('--check');
assert.deepEqual(process.argv.slice(2),check?['--check']:[]);
for(const output of outputs){const target=path.resolve(root,output);if(check)assert.deepEqual(readFileSync(target),source,target);else{mkdirSync(path.dirname(target),{recursive:true});writeFileSync(target,source);}}
console.log(`Local market acceptance profile ${check?'checked':'synchronized'}; explicit isolated mode only.`);
